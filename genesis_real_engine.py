class CircuitBreaker:
    """Agar disk full ho ya error loop bane toh execution safely abort karta hai."""
    MAX_PROPOSALS = 50

    @classmethod
    def check_safety(cls, base_dir="vault/proposals"):
        if os.path.exists(base_dir):
            count = len(os.listdir(base_dir))
            if count >= cls.MAX_PROPOSALS:
                raise SystemError(f"CIRCUIT BREAKER TRIGGERED: Too many unapproved proposals ({count}).")

