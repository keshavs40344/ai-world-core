# UPDATE 1: REAL-WORLD LIVE NETWORK HARVESTER (Zero-Auth Open Feed)
# =====================================================================
class LiveSignalHarvester:
    """Network se real, un-cached XML pull karta hai."""
    @staticmethod
    def harvest():
        url = "https://news.ycombinator.com/rss"
        req = urllib.request.Request(url, headers={'User-Agent': 'Mozilla/5.0 (GenesisCore/1.0)'})
        try:
            with urllib.request.urlopen(req, timeout=8) as response:
                root = ET.fromstring(response.read())
                item = root.find('.//channel/item')
                title = item.find('title').text
                link = item.find('link').text
                return {"title": title, "link": link}
        except Exception as e:
            return {"title": f"Local Fallback Directive {int(time.time())}", "link": "https://localhost"}

