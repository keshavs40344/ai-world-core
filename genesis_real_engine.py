# UPDATE 4: STATIC SECURITY AUDITOR (Real AST Scanner)
# =====================================================================
class StaticSecurityAuditor:
    """Dangerous calls (eval, exec, rm -rf) ko file me scan karta hai."""
    BANNED_TOKENS = ["__import__", "eval(", "exec(", "os.system('rm", "shutil.rmtree"]
    
    @classmethod
    def audit(cls, file_path):
        with open(file_path, "r", encoding="utf-8") as f:
            content = f.read()
        for token in cls.BANNED_TOKENS:
            if token in content:
                return False, f"Flagged insecure token: {token}"
        return True, "Security Check Passed"

