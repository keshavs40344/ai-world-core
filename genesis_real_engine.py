# UPDATE 9: PERSISTENT SQLITE SKILL & TELEMETRY VAULT
# =====================================================================
class PersistenceEngine:
    """Relational database par table banakar records persist karta hai."""
    DB_PATH = "vault/genesis_memory.db"

    @classmethod
    def init_db(cls):
        os.makedirs("vault", exist_ok=True)
        conn = sqlite3.connect(cls.DB_PATH)
        cur = conn.cursor()
        cur.execute("""
            CREATE TABLE IF NOT EXISTS telemetry (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                timestamp TEXT,
                signal_title TEXT,
                qa_status TEXT,
                artifact_path TEXT
            )
        """)
        conn.commit()
        conn.close()

    @classmethod
    def record(cls, title, qa_status, path):
        conn = sqlite3.connect(cls.DB_PATH)
        cur = conn.cursor()
        cur.execute("INSERT INTO telemetry (timestamp, signal_title, qa_status, artifact_path) VALUES (?, ?, ?, ?)",
                    (datetime.now(timezone.utc).isoformat(), title, qa_status, path))
        conn.commit()
        conn.close()

